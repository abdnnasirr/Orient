#!/usr/bin/env node
import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, readlinkSync, renameSync, symlinkSync, unlinkSync, writeFileSync, copyFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { REPO, USER_HOME, CODEX_HOME, STATE, SETTINGS, START, END, agent, agentInstructions, guidance, settings, shellQuote, codexExecutable, isMain } from "./runtime.mjs";
import { readSelfImprover } from "../../hooks/self-improver.mjs";

export function managedBlock(existing, content) {
  const start = existing.indexOf(START), end = existing.indexOf(END);
  const block = `${START}\n${content.trim()}\n${END}`;
  if ((start < 0) !== (end < 0) || (start >= 0 && (end < start || existing.indexOf(START, start + START.length) >= 0 || existing.indexOf(END, end + END.length) >= 0))) {
    throw new Error("Ambiguous Orient markers in AGENTS.md; left untouched.");
  }
  if (start < 0) return existing.trimEnd() + (existing.trim() ? "\n\n" : "") + block + "\n";
  return existing.slice(0, start) + block + existing.slice(end + END.length);
}

function read(file, fallback = "") { return existsSync(file) ? readFileSync(file, "utf8") : fallback; }
function stat(file) { try { return lstatSync(file); } catch (e) { if (e.code === "ENOENT") return null; throw e; } }

export function install({ apply = false, preferencesFile, codexBin, quiet = false } = {}) {
  const previous = settings();
  const config = { ...previous, repo: REPO, codexHome: CODEX_HOME };
  if (preferencesFile) config.preferencesFile = resolve(preferencesFile);
  if (codexBin) config.codexBin = resolve(codexBin);
  const operations = [], conflicts = [];
  const write = (file, content, owned = false) => {
    const entry = stat(file);
    if (entry?.isSymbolicLink() || (entry && !entry.isFile())) throw new Error(`Refusing to replace ${file}: not a regular file.`);
    const existing = read(file);
    if (entry && owned && !existing.startsWith("# Generated by Orient's Codex adapter.")) throw new Error(`Existing agent is not owned by Orient: ${file}`);
    if (existing !== content) operations.push({ type: "write", file, content, existed: Boolean(entry) });
  };
  const skillDir = join(USER_HOME, ".agents", "skills");
  for (const item of readdirSync(join(REPO, "skills"), { withFileTypes: true })) {
    if (!item.isDirectory() || !existsSync(join(REPO, "skills", item.name, "SKILL.md"))) continue;
    const target = join(REPO, "skills", item.name), file = join(skillDir, item.name), entry = stat(file);
    if (entry && !entry.isSymbolicLink()) { conflicts.push(file); continue; }
    if (entry) {
      const oldTarget = resolve(dirname(file), readlinkSync(file));
      if (oldTarget === target) continue;
      if (!previous.repo || oldTarget !== join(previous.repo, "skills", item.name)) { conflicts.push(file); continue; }
    }
    operations.push({ type: "link", file, target, existed: Boolean(entry) });
  }
  if (conflicts.length) throw new Error(`Existing skill folders were left untouched. Resolve these conflicts before installing:\n${conflicts.join("\n")}`);
  const override = join(CODEX_HOME, "AGENTS.override.md");
  if (read(override).trim()) throw new Error(`A non-empty ${override} overrides AGENTS.md. Resolve it before installing.`);
  const global = join(CODEX_HOME, "AGENTS.md");
  write(global, managedBlock(read(global), guidance(config)));
  for (const name of ["execute", "critique", "self-improve"]) {
    const role = agent(name);
    const content = "# Generated by Orient's Codex adapter. Edit agents/ in the shared repo.\n" +
      `name = ${JSON.stringify(name)}\ndescription = ${JSON.stringify(role.description)}\ndeveloper_instructions = ${JSON.stringify(agentInstructions(name, config))}\n`;
    write(join(CODEX_HOME, "agents", `${name}.toml`), content, true);
  }
  const hookPath = join(CODEX_HOME, "hooks.json");
  const hooks = JSON.parse(read(hookPath, "{}"));
  if (!hooks || typeof hooks !== "object" || Array.isArray(hooks) || (hooks.hooks && (typeof hooks.hooks !== "object" || Array.isArray(hooks.hooks)))) throw new Error("Invalid existing hooks.json; left untouched.");
  hooks.hooks ||= {};
  const commands = [];
  const ownedCommands = new Set(previous.hookCommands || []);
  for (const [event, groups] of Object.entries(hooks.hooks)) {
    if (!Array.isArray(groups)) throw new Error(`Invalid hooks.json event: ${event}`);
    hooks.hooks[event] = groups.map(group => ({ ...group, hooks: (group.hooks || []).filter(hook => !ownedCommands.has(hook.command)) })).filter(group => group.hooks.length);
  }
  const add = (event, script, matcher) => {
    const command = `${shellQuote(process.execPath)} ${shellQuote(join(REPO, script))}`;
    commands.push(command);
    (hooks.hooks[event] ||= []).push({ ...(matcher ? { matcher } : {}), hooks: [{ type: "command", command, ...(event === "SessionStart" ? { additionalContextLimit: 32000 } : {}) }] });
  };
  add("SessionStart", "adapters/codex/session-start.mjs", "startup|resume|clear|compact|fork");
  if (readSelfImprover(join(USER_HOME, ".orient")) === "codex") add("PreCompact", "adapters/codex/pre-compact.mjs");
  add("PostToolUse", "adapters/codex/skill-usage.mjs");
  config.hookCommands = commands;
  write(hookPath, JSON.stringify(hooks, null, 2) + "\n");
  write(SETTINGS, JSON.stringify(config, null, 2) + "\n");
  // Preflight all generated files before changing anything. One backup per install
  // batch keeps unrelated user settings and guidance recoverable.
  let backup;
  if (apply && operations.length) {
    backup = join(STATE, "backups", new Date().toISOString().replace(/[:.]/g, "-"));
    for (let i = 0; i < operations.length; i++) {
      const op = operations[i];
      mkdirSync(dirname(op.file), { recursive: true });
      if (op.existed && op.type === "write") {
        mkdirSync(backup, { recursive: true });
        copyFileSync(op.file, join(backup, `${i}-${op.file.split(/[\\/]/).pop()}`));
      }
      if (op.type === "link") {
        if (op.existed) unlinkSync(op.file);
        symlinkSync(op.target, op.file, process.platform === "win32" ? "junction" : "dir");
      } else {
        const temp = `${op.file}.orient-${process.pid}`;
        writeFileSync(temp, op.content, { mode: 0o600 });
        renameSync(temp, op.file);
      }
    }
    if (backup && existsSync(backup)) writeFileSync(join(backup, "operations.json"), JSON.stringify(operations.map(({ content, ...op }) => op), null, 2));
  }
  if (!quiet) {
    for (const op of operations) console.log(`${apply ? "APPLIED" : "WOULD"} ${op.type}: ${op.file}${op.target ? ` -> ${op.target}` : ""}`);
    console.log(operations.length ? `${apply ? "Installed" : "Dry run"}: ${operations.length} changes${backup && existsSync(backup) ? `; backups: ${backup}` : ""}.` : "Already installed; shared files are current.");
    if (apply) console.log("Start a fresh Codex session and review/trust the Orient hooks in /hooks. Existing unrelated settings are preserved.");
  }
  return { operations, config };
}

if (isMain(import.meta.url)) {
  try {
    const args = process.argv.slice(2), allowed = new Set(["--apply", "--preferences", "--codex-bin", "--verify"]);
    for (let i = 0; i < args.length; i++) {
      if (!allowed.has(args[i])) throw new Error(`Unknown option: ${args[i]}`);
      if (["--preferences", "--codex-bin"].includes(args[i])) { if (!args[i + 1] || args[i + 1].startsWith("--")) throw new Error(`Missing value: ${args[i]}`); i++; }
    }
    const option = name => args.includes(name) ? args[args.indexOf(name) + 1] : undefined;
    const result = install({ apply: args.includes("--apply"), preferencesFile: option("--preferences"), codexBin: option("--codex-bin") });
    if (args.includes("--verify")) {
      if (result.operations.length && !args.includes("--apply")) throw new Error("Installation is missing or stale. Apply the printed changes first.");
      console.log(`Codex executable: ${codexExecutable(result.config)}`);
    }
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
